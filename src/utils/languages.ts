export const DEFAULT_LANGUAGE: WorldLanguage = WORLD_LANGUAGES[0];

export function findLanguageByCode(code: string): WorldLanguage {
  const clean = code.trim().toLowerCase();
  const found = WORLD_LANGUAGES.find(
    (l) => l.code.toLowerCase() === clean || l.code.toLowerCase().split('-')[0] === clean.split('-')[0]
  );
  return found || DEFAULT_LANGUAGE;
}

export function getLanguageTestPhrase(code: string, callsign: string = 'Sir Tharun'): string {
  const lang = findLanguageByCode(code);
  let text = lang.sampleGreeting;
  if (callsign && callsign !== 'Sir Tharun') {
    text = text.replace(/Sir Tharun|Tharun|તરુણ|தருண்|తరుణ్|ತರುಣ್|തരുൺ|তরুণ|तरुण/gi, callsign);
  }
  return text;
}
